# ddogs/tools/Build-YuttosVendors.ps1 - the six Yuttos shop NPCs in Nascence Wilds (PF 4311) as content NPCs with a
# vendor window and the live greeting. Positions are the client spawn points (YUME = Yuttos Machines near Mil, per Randy's
# live screenshot 2026-10-14). Stock: only items identified with confidence from the screenshots (see $stock); rest left out.
param([string]$GameData = (Join-Path $PSScriptRoot '..\..\AORebirth\GameData'))
$ErrorActionPreference = 'Stop'
$u = [Text.UTF8Encoding]::new($false)
$GameData = [IO.Path]::GetFullPath($GameData)
$nt = [IO.File]::ReadAllText((Join-Path $GameData 'NpcTemplates.json'), $u) | ConvertFrom-Json
$sp = ([IO.File]::ReadAllText((Join-Path $GameData 'Playfields\4311\Spawns.json'), $u) | ConvertFrom-Json).spawns
# hash at the spawn point, display name, stat donor template (YUMA = captured Yuttos look)
$v = @(@('DEBE','Deep Breath Nine'), @('YUME','Yuttos Machines'), @('YTMA','Yuttos Manuals'), @('YUCH','Yuttos Chemicals'), @('YUPH','Yuttos Pharmaceuticals'), @('YUEL','Yuttos Electronics'), @('YUTO','Yuttos Tools'))
$stock = @{}   # hash -> @(@(lowId, highId, ql), ...): nothing identified with confidence yet
$ppath = Join-Path $GameData 'PlayfieldContent\4311\Npcs.json'
$pf = [IO.File]::ReadAllText($ppath, $u) | ConvertFrom-Json
$donor = if ($nt.YUMA) { $nt.YUMA.Templates[0] } else { throw 'no YUMA donor' }
$keep = @($pf.Npcs | Where-Object { $_.Key -notlike 'ddogs:yuttos:*' })
$ids = @(); $i = 0
foreach ($x in $v) {
  $h, $name = $x; $i++
  $p = $sp | Where-Object hashText -eq $h | Select-Object -First 1
  if (-not $p) { throw "no spawn point $h" }
  $src = $donor
  $inst = 0x7A1C0000 + $i
  $st = [ordered]@{}; foreach ($k in $src.Stats.PSObject.Properties) { $st[$k.Name] = $k.Value }
  $a = [double]$p.angle * [math]::PI / 180
  $items = @(); $slot = 0; foreach ($s in @($stock[$h])) { if ($s) { $items += [ordered]@{ Slot = $slot++; LowId = $s[0]; HighId = $s[1]; Quality = $s[2] } } }
  $keep += [pscustomobject][ordered]@{
    Key = "ddogs:yuttos:$h"; Provenance = "Randy live screenshot 2026-10-14; look from YUMA capture"
    ContentNpcIdentity = ('SimpleChar:{0:X8}' -f $inst); PlayfieldId = 4311; InstanceId = $inst; Name = $name
    Position = @($p.position); Rotation = @(0, [math]::Sin($a / 2), 0, [math]::Cos($a / 2))
    Stats = $st; Passive = $true; Attackable = $false; TickLiving = $false
    Vendor = [ordered]@{ InstanceId = 0x130C0000 + $i; TemplateId = 99634; Stock = $items }
  }
  if ($h -eq 'DEBE') { $debe = ('SimpleChar:{0:X8}' -f $inst); $keep[-1].PSObject.Properties.Remove('Vendor') } else { $ids += ('SimpleChar:{0:X8}' -f $inst) }
}
$pf.Npcs = $keep
# YUMA is now the Machines content NPC: YUMA (315,1542) is the same NPC (Randy 2026-10-14): drop its hash template so there is only one Yuttos Machines.
$nt.PSObject.Properties.Remove('YUMA'); [IO.File]::WriteAllText((Join-Path $GameData 'NpcTemplates.json'), ($nt | ConvertTo-Json -Depth 8) + "`n", $u)
[IO.File]::WriteAllText($ppath, ($pf | ConvertTo-Json -Depth 10), $u)
$k = [ordered]@{
  Notes = 'Yuttos shop NPCs, Nascence Wilds (4311). Live greeting from Randy''s screenshots. Generated by ddogs/tools/Build-YuttosVendors.ps1.'
  Npcs = $ids
  Openers = @([ordered]@{ Say = 'hello' })
  Replies = [ordered]@{ wares = [ordered]@{ Text = 'Canst thou me thy wares show... or whatever.'; Goto = 'shop' }; bye = [ordered]@{ Text = 'Goodbye.'; Goto = 'bye' } }
  Lines = [ordered]@{
    hello = [ordered]@{ Text = 'Weary traveller! I bidth thou welcome to my humble abode. Through my wares browseth and what thou dost find, thou canst keep for a meager embursage.'; Replies = @('wares', 'bye') }
    shop = [ordered]@{ Text = '{shop}' }
    bye = [ordered]@{ Text = '{close}' }
  }
}
[IO.File]::WriteAllText((Join-Path $GameData 'Knubot\YuttosVendor.json'), ($k | ConvertTo-Json -Depth 8), $u)
# Deep Breath Nine's dialog is the Insipid canister trade in Build-NewbieQuests.ps1 (Knubot/DeepBreathNine.json).
"yuttos vendors=$($ids.Count) + Deep Breath Nine"
