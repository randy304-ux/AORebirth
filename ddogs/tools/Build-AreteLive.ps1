function Edit([string]$rel, [scriptblock]$fn) {
    $p = Join-Path $gd $rel; $s = [IO.File]::ReadAllText($p); $n = & $fn $s
    if ($n -eq $s) { throw "no change: $rel" }; [IO.File]::WriteAllText($p, $n, $u); "edited $rel"
}
function Rep([string]$s, [string]$old, [string]$new) {
    if (-not $s.Contains($old) -and $s.Contains("`r`n")) { $old = $old.Replace("`r`n", "`n").Replace("`n", "`r`n"); $new = $new.Replace("`r`n", "`n").Replace("`n", "`r`n") }
    if (-not $s.Contains($old)) { throw "missing: $old" }; $s.Replace($old, $new)
}

